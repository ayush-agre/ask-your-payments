class IdempotencyEngine:
    """
    Cryptographic Idempotency Engine.
    Ensures that every external execution initiated by Ask-Your-Payments possesses
    a deterministic, collision-resistant idempotency key passed directly via APIMatic
    SDK headers. This definitively prevents double-billing across network retries,
    worker restarts, and multi-node execution races.
    """

    @staticmethod
    def generate_idempotency_key(
        operation_id: uuid.UUID,
        operation_type: str,
        payload_hash: str,
        step: str = "primary",
    ) -> str:
        """
        Derives an RFC 7230 compliant idempotency token.
        Format: `recon-{step}-{operation_id[:8]}-{sha256(op_id + payload_hash)[:16]}`
        Max length <= 64 characters (matches ERP OpenAPI schema constraint).
        """
        salt = f"{operation_id}:{operation_type}:{payload_hash}:{step}"
        digest = hashlib.sha256(salt.encode("utf-8")).hexdigest()[:16]
        short_id = str(operation_id).replace("-", "")[:8]
        token = f"recon-{step[:6]}-{short_id}-{digest}"
        return token[:64]


# ---------------------------------------------------------------------------
# HASH-CHAINED AUDIT LOGGER HELPER
# ---------------------------------------------------------------------------
async def append_audit_entry(
    session: AsyncSession,
    entity_type: str,
    entity_id: uuid.UUID,
    action: str,
    actor: str,
    detail: Dict[str, Any],
) -> AuditLog:
    """
    Appends a cryptographically verified, hash-chained entry to the `audit_log` table.
    Guarantees non-repudiation and enterprise auditability for APIMatic-orchestrated
    financial actions.
    """
    detail_str = json.dumps(detail, sort_keys=True, default=str)
    payload_hash = hashlib.sha256(detail_str.encode("utf-8")).hexdigest()

    # Fetch previous chain hash
    prev_stmt = (
        select(AuditLog.chain_hash)
        .order_by(AuditLog.created_at.desc())
        .limit(1)
    )
    res = await session.execute(prev_stmt)
    previous_hash = res.scalar_one_or_none() or ("0" * 64)

    chain_material = f"{previous_hash}{payload_hash}"
    chain_hash = hashlib.sha256(chain_material.encode("utf-8")).hexdigest()

    audit_entry = AuditLog(
        entity_type=entity_type,
        entity_id=entity_id,
        action=action,
        actor=actor,
        detail=detail_str,
        payload_hash=payload_hash,
        previous_hash=previous_hash,
        chain_hash=chain_hash,
    )
    session.add(audit_entry)
    return audit_entry


